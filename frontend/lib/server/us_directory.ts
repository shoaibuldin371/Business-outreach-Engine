export function findStateHub(stateOrCity: string): WorldwideHub | undefined {
  const norm = stateOrCity.toLowerCase().trim();
  return US_STATE_HUBS.find(h => {
    const hubCity = h.city.toLowerCase();
    const stateCode = h.city.split(',')[1]?.trim().toLowerCase();
    return hubCity.includes(norm) || norm.includes(hubCity) || stateCode === norm;
  });
}
